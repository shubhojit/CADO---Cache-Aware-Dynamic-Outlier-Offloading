from __future__ import annotations

"""Create a compact, publication-style summary figure for the CADO experiments.

This script reads the CSV outputs generated by the experiments and plots the main
research story into one composite figure. The design intentionally mirrors the style
of small research repos that focus on a few key visuals instead of a large plotting
stack or notebook-heavy workflow.

The output is a single PNG saved under results/figures/ so it is easy to include in
README pages or blog posts.
"""

import csv
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


ROOT = Path(__file__).resolve().parents[1]
RESULTS_DIR = ROOT / "results"
FIGURE_DIR = RESULTS_DIR / "figures"


def load_csv(path: Path) -> list[dict[str, float | str | int]]:
    """Read a CSV file and return rows as dictionaries.

    Args:
        path: Path to the CSV file.

    Returns:
        A list of dictionaries with the CSV values converted to numeric types where
        appropriate.
    """
    with path.open("r", newline="") as csv_file:
        reader = csv.DictReader(csv_file)
        rows = list(reader)

    normalized: list[dict[str, float | str | int]] = []
    for row in rows:
        clean: dict[str, float | str | int] = {}
        for key, value in row.items():
            try:
                clean[key] = float(value)
            except ValueError:
                clean[key] = value
        normalized.append(clean)
    return normalized


def plot_threshold_sweep(ax: plt.Axes) -> None:
    """Plot how the threshold affects relative error.

    The threshold acts as a proxy for the routing policy: as it increases, only more
    extreme activations are treated as high-precision outliers. The plot shows the
    tradeoff between more selective routing and approximation accuracy.
    """
    rows = load_csv(RESULTS_DIR / "threshold_sweep.csv")
    threshold = np.asarray([row["threshold"] for row in rows], dtype=float)
    cado = np.asarray([row["cado_relative_error"] for row in rows], dtype=float)
    uniform = np.asarray([row["uniform_int8_relative_error"] for row in rows], dtype=float)

    ax.plot(threshold, cado, marker="o", linewidth=2.0, label="CADO")
    ax.plot(threshold, uniform, marker="s", linestyle="--", linewidth=2.0, label="Uniform INT8")
    ax.set_title("Threshold sweep")
    ax.set_xlabel("routing threshold")
    ax.set_ylabel("relative error")
    ax.grid(alpha=0.3)
    ax.legend(loc="best")


def plot_equal_budget(ax: plt.Axes) -> None:
    """Plot the dynamic-vs-static comparison under a fixed precision budget.

    This is the core research result in the repo: both policies are evaluated with the
    same allocation budget, and the question is whether adapting the routing decision
    to the current batch gives a better final accuracy.
    """
    rows = load_csv(RESULTS_DIR / "equal_budget_comparison.csv")
    persistent = [row for row in rows if row["mode"] == "persistent"]
    moving = [row for row in rows if row["mode"] == "moving"]

    def summarize(entries: list[dict[str, float | str | int]]) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        budget = np.asarray([row["budget_fraction"] for row in entries], dtype=float)
        dynamic = np.asarray([row["dynamic_relative_error"] for row in entries], dtype=float)
        static = np.asarray([row["static_relative_error"] for row in entries], dtype=float)
        return budget, dynamic, static

    budget_p, dyn_p, static_p = summarize(persistent)
    budget_m, dyn_m, static_m = summarize(moving)

    ax.plot(budget_p, dyn_p, marker="o", linewidth=2.0, label="Dynamic (persistent)")
    ax.plot(budget_p, static_p, marker="^", linestyle="--", linewidth=2.0, label="Static (persistent)")
    ax.plot(budget_m, dyn_m, marker="D", linewidth=2.0, label="Dynamic (moving)")
    ax.plot(budget_m, static_m, marker="x", linestyle="--", linewidth=2.0, label="Static (moving)")

    ax.set_title("Equal-budget routing comparison")
    ax.set_xlabel("high-precision budget fraction")
    ax.set_ylabel("relative error")
    ax.grid(alpha=0.3)
    ax.legend(loc="best")


def plot_cache_tile_sweep(ax: plt.Axes) -> None:
    """Plot the cache-aware tile sweep as a proxy for fast-memory pressure.

    The idea is to model a working set in which a tile of columns is processed at a
    time and only a limited fraction can stay on the more expensive path. This is a
    simple stand-in for real cache pressure but is still meaningful for the research
    prototype.
    """
    rows = load_csv(RESULTS_DIR / "cache_tile_sweep.csv")
    selected = [
        r for r in rows if float(r["tile_size"]) in {16, 64, 256} and float(r["budget_fraction"]) in {0.05, 0.10, 0.20, 0.30}
    ]

    for tile_size in [16, 64, 256]:
        subset = [r for r in selected if float(r["tile_size"]) == tile_size]
        budget = np.asarray([float(row["budget_fraction"]) for row in subset], dtype=float)
        dynamic = np.asarray([float(row["dynamic_relative_error"]) for row in subset], dtype=float)
        ax.plot(budget, dynamic, marker="o", linewidth=2.0, label=f"tile={tile_size}")

    ax.set_title("Tile-budget sweep")
    ax.set_xlabel("budget fraction per tile")
    ax.set_ylabel("relative error")
    ax.grid(alpha=0.3)
    ax.legend(loc="best")


def main() -> None:
    """Create the final summary figure and save it to the results directory."""
    FIGURE_DIR.mkdir(parents=True, exist_ok=True)

    fig, axes = plt.subplots(1, 3, figsize=(16, 5))
    plot_threshold_sweep(axes[0])
    plot_equal_budget(axes[1])
    plot_cache_tile_sweep(axes[2])

    fig.suptitle("CADO: error-vs-budget summaries", fontsize=14, y=1.02)
    fig.tight_layout()
    out_path = FIGURE_DIR / "cado_summary.png"
    fig.savefig(out_path, dpi=200)
    print(f"saved_png={out_path}")


if __name__ == "__main__":
    main()
